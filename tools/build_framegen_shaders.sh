#!/bin/sh
# Compiles the frame generation shaders (runtime/gpu/vulkan/framegen/*.comp) into the SPIR-V header
# framegen.cpp includes, and validates each with spirv-val. Needs glslangValidator and spirv-val
# (Homebrew `glslang` and `spirv-tools`, or the Vulkan SDK). Run after changing a shader and commit
# the header with it.
set -e
cd "$(dirname "$0")/../runtime/gpu/vulkan/framegen"
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT
{
    echo "// Generated by tools/build_framegen_shaders.sh from the .comp files beside it. Do not edit."
    echo "#pragma once"
} > "$tmp/all.h"
for name in downsample search smooth warp; do
    glslangValidator -V --target-env vulkan1.0 -o "$tmp/$name.spv" "$name.comp" >/dev/null
    spirv-val --target-env vulkan1.0 "$tmp/$name.spv"
    glslangValidator -V --target-env vulkan1.0 --vn "framegen_${name}" -o "$tmp/$name.h" "$name.comp" >/dev/null
    grep -v -e '#pragma once' -e '^[[:space:]]*//' "$tmp/$name.h" >> "$tmp/all.h"
done
mv "$tmp/all.h" shaders.h
echo "wrote runtime/gpu/vulkan/framegen/shaders.h"
